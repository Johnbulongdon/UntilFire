import assert from 'node:assert/strict';
import { buildLadderView } from '../lib/contribution-ladder.ts';
import { ladderToStored, EMPTY_LADDER } from '../lib/contribution.ts';
import { contributionDestinations, contributionWarnings } from '../lib/contribution-presentation.ts';
const today = new Date(2026,10,1,12);
const account = { id:'cash',label:'Test cash',mask:null,subtype:'checking',balance:10000,apy:null,isSavings:false,nativeBalance:10000,currency:'USD',converted:true,syncedAt:today.toISOString() };
const facts = { cashAccounts:[account],today,budgetMonthlySpending:1000,expectedItems:[{id:'pay',type:'income',description:'Pay',amountUSD:3000,dueDate:'2026-11-15',recurrence:'monthly'}] };
const base = ladderToStored({...EMPTY_LADDER,efOverride:'1301',expensesOverride:'1000'});
const view = buildLadderView(base,589,facts,{cadence:'monthly',anchorDay:16});
const before=JSON.stringify(view.waterfall);
const rows=contributionDestinations(view.waterfall.fills);
assert.equal(rows.filter(r=>r.kind==='emergency').length,1);
assert.equal(rows[0].label,'Emergency savings');assert.equal(rows[0].amount,589);
assert.equal(JSON.stringify(view.waterfall),before,'presentation must not mutate the model');
const debt=buildLadderView({...base,debts:[{name:'Card',balance:100,ratePct:30}]},589,facts,{cadence:'monthly',anchorDay:16});
const split=contributionDestinations(debt.waterfall.fills);
assert.equal(split.find(r=>r.kind==='emergency').amount,489);
assert.equal(split.find(r=>r.kind==='high-interest-debt').amount,100);
assert.equal(split.reduce((n,r)=>n+r.amount,0),589);
const investment=buildLadderView({...base,efOverride:6000},589,facts);
assert.equal(contributionDestinations(investment.waterfall.fills)[0].label,'Investments');
assert.deepEqual(contributionDestinations(buildLadderView(base,0,facts).waterfall.fills),[]);
const disabled=buildLadderView({...base,disabled:['emergency-floor','emergency-target']},589,facts);
assert(!contributionDestinations(disabled.waterfall.fills).some(r=>r.kind==='emergency'));
assert.equal(contributionWarnings(view,today).length,0);
const problem={...view,available:{...view.available,forecast:{...view.available.forecast,shortBefore:{iso:'2026-11-07',balance:-355}},cashAccounts:[{...account,syncedAt:'2026-10-01T00:00:00Z'}]}};
assert.deepEqual(contributionWarnings(problem,today).map(w=>w.kind),['shortfall','stale']);
const overridden={...view,budget:99999};
assert(contributionWarnings(overridden,today).some(w=>w.kind==='override'));
const missing=buildLadderView(base,0,{cashAccounts:[],today});
assert(contributionWarnings(missing,today).some(w=>w.kind==='missing'));
assert(contributionWarnings(missing,today).some(w=>w.kind==='spending'));
assert(contributionWarnings({...view,available:{...view.available,cashAccounts:[{...account,converted:false}]}},today).some(w=>w.kind==='currency'));
const nominal=buildLadderView({...base,thresholdOverride:null},0,{...facts,realReturn:.069,inflation:.03});
assert.equal(nominal.thresholdPct,10.1);
console.log('PASS contribution grouping, unchanged allocations/order, debt between stages, disabled stages, zero/investing states, warning priority, stale/missing/FX/override and effective threshold.');
