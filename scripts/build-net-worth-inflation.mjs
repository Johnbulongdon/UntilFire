#!/usr/bin/env node
/**
 * Build lib/net-worth-inflation.ts from the BLS consumer price index.
 *
 *   node scripts/build-net-worth-inflation.mjs            # fetch from api.bls.gov
 *   node scripts/build-net-worth-inflation.mjs cpi.json   # a saved BLS API response
 *
 * To save a response (add &registrationkey=… if you have one):
 *   curl -sS "https://api.bls.gov/publicAPI/v2/timeseries/data/CUUR0000SA0?startyear=2022&endyear=2026&annualaverage=true" -o cpi.json
 *
 * Series CUUR0000SA0: CPI-U, all items, US city average, not seasonally
 * adjusted. The factor is the latest month's index divided by the survey
 * year's annual average, so a 2022-dollar amount times the factor is in
 * that month's dollars. Set BLS_API_KEY to use a registered key; without one
 * the API allows few requests a day.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SURVEY_YEAR = 2022;
const SERIES = 'CUUR0000SA0';

async function load(input) {
  if (input) return JSON.parse(readFileSync(input, 'utf8'));
  const now = new Date().getUTCFullYear();
  const params = new URLSearchParams({ startyear: String(SURVEY_YEAR), endyear: String(now), annualaverage: 'true' });
  if (process.env.BLS_API_KEY) params.set('registrationkey', process.env.BLS_API_KEY);
  const res = await fetch(`https://api.bls.gov/publicAPI/v2/timeseries/data/${SERIES}?${params}`);
  if (!res.ok) throw new Error(`BLS API answered ${res.status}`);
  return res.json();
}

const body = await load(process.argv[2]);
if (body.status !== 'REQUEST_SUCCEEDED') throw new Error(`BLS API: ${body.status} ${JSON.stringify(body.message)}`);
const rows = body.Results.series.find((s) => s.seriesID === SERIES)?.data ?? [];

const months = rows.filter((r) => /^M(0[1-9]|1[0-2])$/.test(r.period)).map((r) => ({ year: Number(r.year), month: Number(r.period.slice(1)), name: r.periodName, value: Number(r.value) }));
const surveyMonths = months.filter((m) => m.year === SURVEY_YEAR);
if (surveyMonths.length !== 12) throw new Error(`expected 12 months of ${SURVEY_YEAR}, got ${surveyMonths.length}`);
const base = surveyMonths.reduce((sum, m) => sum + m.value, 0) / 12;
const published = rows.find((r) => Number(r.year) === SURVEY_YEAR && r.period === 'M13');
if (published && Math.abs(Number(published.value) - base) > 0.01) throw new Error(`${SURVEY_YEAR} average ${base.toFixed(3)} differs from BLS's ${published.value}`);

const latest = months.sort((a, b) => b.year - a.year || b.month - a.month)[0];
const factor = Math.round((latest.value / base) * 10000) / 10000;
if (!(factor > 1 && factor < 1.6)) throw new Error(`implausible factor ${factor}`);
const through = `${latest.name} ${latest.year}`;
console.log(`${SURVEY_YEAR} average ${base.toFixed(3)}${published ? ` (BLS ${published.value})` : ''}; ${through} ${latest.value}; factor ${factor}`);

writeFileSync('lib/net-worth-inflation.ts', `/**
 * US prices since the net-worth survey year, for lib/net-worth-compare.ts.
 *
 * GENERATED by scripts/build-net-worth-inflation.mjs from the BLS consumer
 * price index (${SERIES}: CPI-U, all items, US city average, not seasonally
 * adjusted). Do not edit by hand. ${through}: ${latest.value}; ${SURVEY_YEAR}
 * annual average: ${base.toFixed(3)}.
 */
import type { InflationAdjustment } from './net-worth-compare'

export const NET_WORTH_INFLATION: InflationAdjustment | null = ${JSON.stringify({ factor, through })}
`);
console.log('wrote lib/net-worth-inflation.ts');
