#!/usr/bin/env node
/**
 * Build lib/net-worth-benchmarks.ts from the Federal Reserve's Survey of
 * Consumer Finances summary extract.
 *
 *   curl -LO https://www.federalreserve.gov/econres/files/scfp2022excel.zip
 *   node --experimental-strip-types --no-warnings scripts/build-net-worth-benchmarks.mjs scfp2022excel.zip
 *
 * Every row of the extract is one of five imputations of a household
 * (implicates), each carrying the survey weight WGT, so pooling all rows with
 * their weights is the standard way to estimate the distribution. NETWORTH
 * is in survey-year dollars; AGE is the age of the household's reference
 * person.
 *
 * Before writing anything, the medians are checked against the ones the Fed
 * publishes ("Changes in U.S. Family Finances from 2019 to 2022", Federal
 * Reserve Bulletin, October 2023, Table 2). A mismatch of more than 2% means
 * the wrong file, column or weighting, and the script stops.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { weightedCutpoints } from '../lib/weighted-percentiles.ts';

const YEAR = 2022;
// Medians of family net worth, 2022 dollars, copied from the Fed's Table 2.
// The guard (test:net-worth-compare) checks the committed table against the
// same file.
const PUBLISHED_MEDIANS = JSON.parse(readFileSync('scripts/scf-published-medians.json', 'utf8'));

const input = process.argv[2];
if (!input) throw new Error('usage: build-net-worth-benchmarks.mjs <scfp2022excel.zip | SCFP2022.csv>');

const csv = input.endsWith('.zip')
  ? execFileSync('unzip', ['-p', input, '*.csv'], { maxBuffer: 1 << 30 }).toString()
  : readFileSync(input, 'utf8');
const lines = csv.split(/\r?\n/).filter(Boolean);
const header = lines[0].split(',').map((h) => h.replace(/"/g, '').trim().toUpperCase());
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`column ${name} not found`);
  return i;
};
const [iNet, iWgt, iAge] = [col('NETWORTH'), col('WGT'), col('AGE')];

const band = (age) => age < 35 ? 'under_35' : age < 45 ? '35_44' : age < 55 ? '45_54' : age < 65 ? '55_64' : age < 75 ? '65_74' : '75_plus';
const groups = { all: [], under_35: [], '35_44': [], '45_54': [], '55_64': [], '65_74': [], '75_plus': [] };
for (const line of lines.slice(1)) {
  const f = line.split(',');
  const row = { value: Number(f[iNet]), weight: Number(f[iWgt]) };
  const age = Number(f[iAge]);
  if (!Number.isFinite(row.value) || !Number.isFinite(row.weight) || !Number.isFinite(age)) continue;
  groups.all.push(row);
  groups[band(age)].push(row);
}

const bands = Object.fromEntries(Object.entries(groups).map(([k, rows]) => [k, weightedCutpoints(rows).map((v) => Math.round(v))]));
let bad = 0;
for (const [k, cuts] of Object.entries(bands)) {
  const ours = cuts[49];
  const theirs = PUBLISHED_MEDIANS[k];
  const off = Math.abs(ours - theirs) / theirs;
  console.log(`${k.padEnd(9)} rows ${String(groups[k].length).padStart(6)}  median ${ours}  published ${theirs}  ${(off * 100).toFixed(2)}%`);
  if (!(off <= 0.02)) bad++;
}
if (bad) throw new Error(`${bad} median(s) differ from the Fed's by more than 2%; not writing`);

const out = `/**
 * US household net worth by age: cutpoints at 1% … 99%, ${YEAR} dollars.
 *
 * GENERATED by scripts/build-net-worth-benchmarks.mjs from the Federal
 * Reserve's ${YEAR} Survey of Consumer Finances summary extract (all five
 * implicates, weighted by WGT). Do not edit by hand. Medians were checked
 * against the Fed's published Table 2 before this file was written.
 */
import type { NetWorthBenchmarks } from './net-worth-compare'

export const NET_WORTH_BENCHMARKS: NetWorthBenchmarks = ${JSON.stringify({ year: YEAR, bands }, null, 2)}
`;
writeFileSync('lib/net-worth-benchmarks.ts', out);
console.log('wrote lib/net-worth-benchmarks.ts');
